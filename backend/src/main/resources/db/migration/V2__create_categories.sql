-- Menu categories (Burgers, Sandwiches, ...). French fields are optional; English is the fallback.
CREATE TABLE categories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(80)  NOT NULL,
    name_fr         VARCHAR(80),
    slug            VARCHAR(100) NOT NULL,
    description     VARCHAR(500),
    description_fr  VARCHAR(500),
    display_order   INTEGER      NOT NULL DEFAULT 0,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255),
    CONSTRAINT uk_categories_slug UNIQUE (slug)
);

CREATE UNIQUE INDEX ux_categories_name ON categories (lower(name));
CREATE INDEX ix_categories_display_order ON categories (display_order, id);
