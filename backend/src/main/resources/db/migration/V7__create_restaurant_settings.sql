-- Restaurant profile managed from admin -> Settings (single row) and the weekly opening hours.
CREATE TABLE restaurant_settings (
    id                  SMALLINT      PRIMARY KEY DEFAULT 1,
    name                VARCHAR(80)   NOT NULL,
    tagline             VARCHAR(200),
    tagline_fr          VARCHAR(200),
    description         VARCHAR(1000),
    description_fr      VARCHAR(1000),
    address_line        VARCHAR(200),
    city                VARCHAR(100),
    postal_code         VARCHAR(20),
    country             VARCHAR(100),
    phone               VARCHAR(40),
    email               VARCHAR(255),
    map_url             VARCHAR(1000),
    latitude            NUMERIC(9, 6),
    longitude           NUMERIC(9, 6),
    instagram_url       VARCHAR(500),
    facebook_url        VARCHAR(500),
    tiktok_url          VARCHAR(500),
    currency_code       VARCHAR(3)    NOT NULL DEFAULT 'USD',
    announcement        VARCHAR(200),
    announcement_fr     VARCHAR(200),
    promo_enabled       BOOLEAN       NOT NULL DEFAULT FALSE,
    promo_title         VARCHAR(120),
    promo_title_fr      VARCHAR(120),
    promo_text          VARCHAR(500),
    promo_text_fr       VARCHAR(500),
    promo_menu_item_id  BIGINT,
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_by          VARCHAR(255),
    CONSTRAINT ck_restaurant_settings_singleton CHECK (id = 1),
    CONSTRAINT fk_restaurant_settings_promo_item FOREIGN KEY (promo_menu_item_id)
        REFERENCES menu_items (id) ON DELETE SET NULL
);

-- ISO day of week: 1 = Monday ... 7 = Sunday. closes_at earlier than opens_at means "after midnight".
CREATE TABLE opening_hours (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week  SMALLINT NOT NULL,
    opens_at     TIME,
    closes_at    TIME,
    closed       BOOLEAN  NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_opening_hours_day UNIQUE (day_of_week),
    CONSTRAINT ck_opening_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_opening_hours_times CHECK (closed OR (opens_at IS NOT NULL AND closes_at IS NOT NULL))
);

