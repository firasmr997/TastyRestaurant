-- Messages sent from the public contact form.
CREATE TABLE contact_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120)  NOT NULL,
    email       VARCHAR(255)  NOT NULL,
    phone       VARCHAR(40),
    message     VARCHAR(4000) NOT NULL,
    status      VARCHAR(20)   NOT NULL DEFAULT 'NEW',
    locale      VARCHAR(5),
    read_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_contact_messages_status CHECK (status IN ('NEW', 'READ', 'ARCHIVED'))
);

CREATE INDEX ix_contact_messages_status_created ON contact_messages (status, created_at DESC);
CREATE INDEX ix_contact_messages_created ON contact_messages (created_at DESC);
