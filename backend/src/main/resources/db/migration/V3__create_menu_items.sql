-- Dishes. A category cannot be deleted while dishes reference it (ON DELETE RESTRICT);
-- the API offers reassignment instead. Ingredients are stored as a comma-separated list.
CREATE TABLE menu_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id      BIGINT        NOT NULL,
    name             VARCHAR(120)  NOT NULL,
    name_fr          VARCHAR(120),
    slug             VARCHAR(140)  NOT NULL,
    description      VARCHAR(1000) NOT NULL,
    description_fr   VARCHAR(1000),
    ingredients      VARCHAR(1000),
    ingredients_fr   VARCHAR(1000),
    price            NUMERIC(10, 2) NOT NULL,
    main_image_url   VARCHAR(1000),
    main_image_key   VARCHAR(500),
    main_image_alt   VARCHAR(255),
    available        BOOLEAN       NOT NULL DEFAULT TRUE,
    featured         BOOLEAN       NOT NULL DEFAULT FALSE,
    vegetarian       BOOLEAN       NOT NULL DEFAULT FALSE,
    spicy            BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by       VARCHAR(255),
    updated_by       VARCHAR(255),
    CONSTRAINT uk_menu_items_slug UNIQUE (slug),
    CONSTRAINT ck_menu_items_price CHECK (price >= 0),
    CONSTRAINT fk_menu_items_category FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE RESTRICT
);

CREATE INDEX ix_menu_items_category ON menu_items (category_id);
CREATE INDEX ix_menu_items_featured ON menu_items (featured) WHERE featured;
CREATE INDEX ix_menu_items_created_at ON menu_items (created_at DESC);
