-- Food and restaurant photography. Food group: FOOD, SANDWICH, BURGER, PLATE, DESSERT, DRINK.
-- Restaurant group: EXTERIOR, INTERIOR, DINING, KITCHEN, BAR, TEAM, ATMOSPHERE.
CREATE TABLE gallery_images (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(150)  NOT NULL,
    title_fr        VARCHAR(150),
    description     VARCHAR(600),
    description_fr  VARCHAR(600),
    image_url       VARCHAR(1000) NOT NULL,
    storage_key     VARCHAR(500),
    alt_text        VARCHAR(255),
    category        VARCHAR(30)   NOT NULL,
    display_order   INTEGER       NOT NULL DEFAULT 0,
    featured        BOOLEAN       NOT NULL DEFAULT FALSE,
    menu_item_id    BIGINT,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255),
    CONSTRAINT ck_gallery_images_category CHECK (category IN (
        'FOOD', 'SANDWICH', 'BURGER', 'PLATE', 'DESSERT', 'DRINK',
        'EXTERIOR', 'INTERIOR', 'DINING', 'KITCHEN', 'BAR', 'TEAM', 'ATMOSPHERE')),
    CONSTRAINT fk_gallery_images_menu_item FOREIGN KEY (menu_item_id)
        REFERENCES menu_items (id) ON DELETE SET NULL
);

CREATE INDEX ix_gallery_images_category ON gallery_images (category, display_order, id);
CREATE INDEX ix_gallery_images_featured ON gallery_images (featured) WHERE featured;
