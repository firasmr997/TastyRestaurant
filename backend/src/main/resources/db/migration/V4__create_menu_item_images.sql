-- Additional photos for a dish (the main photo lives on menu_items).
CREATE TABLE menu_item_images (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id  BIGINT        NOT NULL,
    image_url     VARCHAR(1000) NOT NULL,
    storage_key   VARCHAR(500),
    alt_text      VARCHAR(255),
    sort_order    INTEGER       NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_menu_item_images_item FOREIGN KEY (menu_item_id)
        REFERENCES menu_items (id) ON DELETE CASCADE
);

CREATE INDEX ix_menu_item_images_item ON menu_item_images (menu_item_id, sort_order);
